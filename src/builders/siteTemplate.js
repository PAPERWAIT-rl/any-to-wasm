const fs = require('fs');
const path = require('path');

const SHARED_CSS = fs.readFileSync(
  path.join(__dirname, '..', '..', 'templates', 'site', 'shared-style.css'),
  'utf8'
);

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[c]));
}

